def build_html() -> str:
    css = (
        f"body {{ color:{theme.TEXT}; font-size:13px; line-height:1.6; }}"
        f"h2 {{ color:{theme.ACCENT}; margin-top:26px; margin-bottom:4px; }}"
        f"h4 {{ margin-bottom:2px; margin-top:12px; }}"
        f"li {{ margin-bottom:4px; }}"
        f"td {{ border-bottom:1px solid {theme.BORDER}; }}"
    )
    parts = [f"<style>{css}</style>"]
    for anchor, title, body in SECTIONS:
        parts.append(f'<a name="{anchor}"></a><h2>{title}</h2>{body}')
    return "".join(parts)


class GuideDialog(QDialog):
    def __init__(self, parent=None):
        super().__init__(parent)
        self.setWindowTitle("使い方ノート")
        self.resize(860, 640)
        self.setStyleSheet(theme.STYLESHEET)

        outer = QVBoxLayout(self)
        outer.setContentsMargins(16, 14, 16, 14)
        outer.setSpacing(10)

        body = QHBoxLayout()
        body.setSpacing(12)

        self.toc = QListWidget()
        self.toc.setFixedWidth(190)
        for anchor, title, _ in SECTIONS:
            item = QListWidgetItem(title)
            item.setData(Qt.UserRole, anchor)
            self.toc.addItem(item)
        self.toc.currentItemChanged.connect(self._on_toc)
        body.addWidget(self.toc)

        self.view = QTextBrowser()
        self.view.setOpenExternalLinks(True)
        self.view.setHtml(build_html())
        body.addWidget(self.view, 1)
        outer.addLayout(body, 1)

        close = QPushButton("閉じる")
        close.clicked.connect(self.accept)
        row = QHBoxLayout()
        row.addStretch(1)
        row.addWidget(close)
        outer.addLayout(row)

        self.toc.setCurrentRow(0)

    def _on_toc(self, item: QListWidgetItem | None, _previous=None) -> None:
        if item is not None:
            self.view.scrollToAnchor(item.data(Qt.UserRole))
